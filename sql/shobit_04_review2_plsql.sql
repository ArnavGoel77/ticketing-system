-- ----------------------------------------------------------------------------
-- 1. SCHEMA EXTENSION: EMPLOYEE_AUDIT_LOGS
-- Captures department transfers and role promotions/demotions.
-- ----------------------------------------------------------------------------
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE EMPLOYEE_AUDIT_LOGS (
        audit_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        employee_id       NUMBER NOT NULL,
        old_department_id NUMBER,
        new_department_id NUMBER,
        old_role          VARCHAR2(20),
        new_role          VARCHAR2(20),
        modified_by_user  VARCHAR2(100) DEFAULT USER,
        modified_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
    )';
    DBMS_OUTPUT.PUT_LINE('Table EMPLOYEE_AUDIT_LOGS created successfully.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('Table EMPLOYEE_AUDIT_LOGS already exists.');
        ELSE
            RAISE;
        END IF;
END;
/

-- ----------------------------------------------------------------------------
-- 2. PL/SQL TRIGGER 1: TRG_EMPLOYEE_AUDIT_TRAIL
-- Fires AFTER UPDATE ON EMPLOYEES. Logs department or role reassignments.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER TRG_EMPLOYEE_AUDIT_TRAIL
AFTER UPDATE ON EMPLOYEES
FOR EACH ROW
BEGIN
    IF (:OLD.department_id != :NEW.department_id) OR (:OLD.role != :NEW.role) THEN
        INSERT INTO EMPLOYEE_AUDIT_LOGS (
            employee_id, old_department_id, new_department_id, old_role, new_role, modified_by_user, modified_at
        ) VALUES (
            :NEW.employee_id, :OLD.department_id, :NEW.department_id, :OLD.role, :NEW.role, USER, SYSTIMESTAMP
        );
    END IF;
END;
/

-- ----------------------------------------------------------------------------
-- 3. PL/SQL TRIGGER 2: TRG_PREVENT_DEPT_DELETION_WITH_STAFF
-- Enforces integrity: prevents deleting a department if active staff exist.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER TRG_PREVENT_DEPT_DELETION_WITH_STAFF
BEFORE DELETE ON DEPARTMENTS
FOR EACH ROW
DECLARE
    v_staff_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_staff_count
    FROM EMPLOYEES
    WHERE department_id = :OLD.department_id;

    IF v_staff_count > 0 THEN
        RAISE_APPLICATION_ERROR(-20010, 'INTEGRITY VIOLATION: Cannot delete department "' || :OLD.department_name || '" because ' || v_staff_count || ' employee(s) are currently assigned to it.');
    END IF;
END;
/

-- ----------------------------------------------------------------------------
-- 4. PL/SQL STORED PROCEDURE: SP_TRANSFER_EMPLOYEE_DEPT
-- Atomic personnel reassignment with existence checking and formatted confirmation.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SP_TRANSFER_EMPLOYEE_DEPT (
    p_employee_id       IN  NUMBER,
    p_new_department_id IN  NUMBER,
    p_result_message    OUT VARCHAR2
) IS
    v_emp_name   VARCHAR2(100);
    v_dept_name  VARCHAR2(100);
    v_building   VARCHAR2(100);
    v_curr_dept  NUMBER;
BEGIN
    -- Check employee existence
    SELECT full_name, department_id INTO v_emp_name, v_curr_dept
    FROM EMPLOYEES
    WHERE employee_id = p_employee_id;

    IF v_curr_dept = p_new_department_id THEN
        p_result_message := 'WARNING: Employee ' || v_emp_name || ' is already in Department #' || p_new_department_id || '.';
        RETURN;
    END IF;

    -- Check department existence
    SELECT department_name, location_building INTO v_dept_name, v_building
    FROM DEPARTMENTS
    WHERE department_id = p_new_department_id;

    -- Update department
    UPDATE EMPLOYEES
    SET department_id = p_new_department_id
    WHERE employee_id = p_employee_id;

    COMMIT;
    p_result_message := 'SUCCESS: Transferred ' || v_emp_name || ' to ' || v_dept_name || ' (' || v_building || ').';

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        p_result_message := 'ERROR: Invalid employee ID #' || p_employee_id || ' or department ID #' || p_new_department_id || '.';
        RAISE_APPLICATION_ERROR(-20011, p_result_message);
    WHEN OTHERS THEN
        ROLLBACK;
        p_result_message := 'TRANSFER FAILED: ' || SQLERRM;
        RAISE_APPLICATION_ERROR(-20012, p_result_message);
END;
/

-- ----------------------------------------------------------------------------
-- 5. PL/SQL STORED FUNCTION: FN_GET_TECH_WORKLOAD_SCORE
-- Computes the operational score of a technician based on active vs resolved load.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION FN_GET_TECH_WORKLOAD_SCORE (
    p_technician_id IN NUMBER
) RETURN NUMBER IS
    v_active_load NUMBER := 0;
    v_resolved_load NUMBER := 0;
BEGIN
    SELECT COUNT(*) INTO v_active_load
    FROM TICKETS
    WHERE assigned_to = p_technician_id AND status = 'IN_PROGRESS';

    SELECT COUNT(*) INTO v_resolved_load
    FROM TICKET_RESOLUTIONS
    WHERE technician_id = p_technician_id;

    RETURN (v_active_load * 3) + v_resolved_load;
END;
/

-- ----------------------------------------------------------------------------
-- 6. PL/SQL EXPLICIT CURSOR PROCEDURE: SP_DEPT_STAFF_REPORT
-- Parameterized cursor loop analyzing technician-to-user ratio per department.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SP_DEPT_STAFF_REPORT IS
    CURSOR cur_depts IS
        SELECT department_id, department_name, location_building FROM DEPARTMENTS;

    CURSOR cur_dept_staff(cp_dept_id NUMBER) IS
        SELECT full_name, role FROM EMPLOYEES WHERE department_id = cp_dept_id;

    v_tech_count NUMBER;
    v_user_count NUMBER;
BEGIN
    FOR d IN cur_depts LOOP
        v_tech_count := 0;
        v_user_count := 0;

        FOR s IN cur_dept_staff(d.department_id) LOOP
            IF s.role = 'TECHNICIAN' THEN
                v_tech_count := v_tech_count + 1;
            ELSIF s.role = 'USER' THEN
                v_user_count := v_user_count + 1;
            END IF;
        END LOOP;

        DBMS_OUTPUT.PUT_LINE('Dept: ' || RPAD(d.department_name, 22) || ' | Techs: ' || v_tech_count || ' | Users: ' || v_user_count);
        IF v_tech_count = 0 THEN
            DBMS_OUTPUT.PUT_LINE('  --> [WARNING] No support engineers assigned to ' || d.department_name || '!');
        END IF;
    END LOOP;
END;
/
