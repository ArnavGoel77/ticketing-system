-- 1.3 ADD CONSTRAINT: Add a check constraint to prevent empty resolution notes
ALTER TABLE TICKET_RESOLUTIONS 
ADD CONSTRAINT chk_notes_nonempty 
CHECK (LENGTH(TRIM(resolution_notes)) > 0);

-- 1.4 DROP CONSTRAINT: Demonstrate removal of a named constraint
