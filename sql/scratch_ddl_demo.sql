-- ----------------------------------------------------------------------------
-- PART 2: SAFE DROP TABLE DEMONSTRATION
-- ----------------------------------------------------------------------------

-- Create a temporary scratch table to demonstrate DROP TABLE safely without
-- corrupting the core relational schema:
CREATE TABLE TEMP_INCIDENT_STAGING (
    staging_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_ref   NUMBER,
    raw_payload  VARCHAR2(500),
    imported_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Insert dummy row to prove table exists and is active:
INSERT INTO TEMP_INCIDENT_STAGING (ticket_ref, raw_payload) 
VALUES (9999, 'Test webhook raw payload from third-party monitoring system');

COMMIT;

-- Verify table exists and row is present:
SELECT * FROM TEMP_INCIDENT_STAGING;

-- Execute DROP TABLE with PURGE (removes table completely from the Oracle recyclebin):
DROP TABLE TEMP_INCIDENT_STAGING PURGE;

