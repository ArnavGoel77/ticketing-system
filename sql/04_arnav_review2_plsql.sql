-- ----------------------------------------------------------------------------
-- 1. SCHEMA EXTENSION: TICKET_AUDIT_LOGS
-- Captures row-level mutations (status, priority, assignment) across ticket lifecycle.
-- ----------------------------------------------------------------------------
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE TICKET_AUDIT_LOGS (
        audit_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ticket_id        NUMBER NOT NULL,
        old_status       VARCHAR2(20),
        new_status       VARCHAR2(20),
        old_priority     VARCHAR2(20),
        new_priority     VARCHAR2(20),
        action_type      VARCHAR2(10) NOT NULL CHECK (action_type IN (''UPDATE'', ''DELETE'', ''INSERT'')),
        changed_by_user  VARCHAR2(100) DEFAULT USER,
        changed_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
    )';
    DBMS_OUTPUT.PUT_LINE('Table TICKET_AUDIT_LOGS created successfully.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('Table TICKET_AUDIT_LOGS already exists.');
        ELSE
            RAISE;
        END IF;
END;
/

-- ----------------------------------------------------------------------------
-- 2. PL/SQL TRIGGER 1: TRG_TICKET_AUDIT_TRAIL
-- Fires AFTER UPDATE OR DELETE on TICKETS.
-- Records :OLD vs :NEW pseudorecords for status & priority state transitions.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER TRG_TICKET_AUDIT_TRAIL
AFTER UPDATE OR DELETE ON TICKETS
FOR EACH ROW
DECLARE
    v_action VARCHAR2(10);
    v_user   VARCHAR2(100);
BEGIN
    -- Determine current user context
    v_user := NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), USER);

    IF DELETING THEN
        v_action := 'DELETE';
        INSERT INTO TICKET_AUDIT_LOGS (
            ticket_id, old_status, new_status, old_priority, new_priority, action_type, changed_by_user, changed_at
        ) VALUES (
            :OLD.ticket_id, :OLD.status, NULL, :OLD.priority_level, NULL, v_action, v_user, SYSTIMESTAMP
        );
    ELSIF UPDATING THEN
        v_action := 'UPDATE';
        -- Audit trigger fires only when status, priority, or assignment changes
        IF (:OLD.status != :NEW.status) OR 
           (:OLD.priority_level != :NEW.priority_level) OR 
           (:OLD.assigned_to IS NULL AND :NEW.assigned_to IS NOT NULL) OR 
           (:OLD.assigned_to != :NEW.assigned_to) THEN
            
            INSERT INTO TICKET_AUDIT_LOGS (
                ticket_id, old_status, new_status, old_priority, new_priority, action_type, changed_by_user, changed_at
            ) VALUES (
                :NEW.ticket_id, :OLD.status, :NEW.status, :OLD.priority_level, :NEW.priority_level, v_action, v_user, SYSTIMESTAMP
            );
        END IF;
    END IF;
END;
/

-- ----------------------------------------------------------------------------
-- 3. PL/SQL TRIGGER 2: TRG_AUTO_RESOLVE_STATUS
-- Fires AFTER INSERT on TICKET_RESOLUTIONS.
-- Automatically synchronizes parent TICKETS status to 'RESOLVED'.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER TRG_AUTO_RESOLVE_STATUS
AFTER INSERT ON TICKET_RESOLUTIONS
FOR EACH ROW
BEGIN
    UPDATE TICKETS
    SET status = 'RESOLVED'
    WHERE ticket_id = :NEW.ticket_id;
END;
/

-- ----------------------------------------------------------------------------
-- 4. PL/SQL STORED PROCEDURE: SP_RESOLVE_INCIDENT_TRANSACTION
-- Multi-step atomic transaction with IN & OUT parameters, SAVEPOINT, and ACID rollback.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SP_RESOLVE_INCIDENT_TRANSACTION (
    p_ticket_id        IN  NUMBER,
    p_technician_id    IN  NUMBER,
    p_resolution_notes IN  VARCHAR2,
    p_status_message   OUT VARCHAR2
) IS
    v_current_status VARCHAR2(20);
    v_tech_role      VARCHAR2(20);
    e_ticket_already_resolved EXCEPTION;
    e_invalid_technician      EXCEPTION;
    e_empty_notes             EXCEPTION;
BEGIN
    -- 1. Input Validation: Check resolution notes
    IF TRIM(p_resolution_notes) IS NULL THEN
        RAISE e_empty_notes;
    END IF;

    -- 2. Verify Ticket Exists and Is Not Already Resolved
    SELECT status INTO v_current_status
    FROM TICKETS
    WHERE ticket_id = p_ticket_id;

    IF v_current_status IN ('RESOLVED', 'CLOSED') THEN
        RAISE e_ticket_already_resolved;
    END IF;

    -- 3. Verify Technician Role
    SELECT role INTO v_tech_role
    FROM EMPLOYEES
    WHERE employee_id = p_technician_id;

    IF v_tech_role NOT IN ('TECHNICIAN', 'ADMIN') THEN
        RAISE e_invalid_technician;
    END IF;

    -- 4. Establish Transaction Boundary
    SAVEPOINT before_incident_resolution;

    -- 5. Insert Resolution Record
    INSERT INTO TICKET_RESOLUTIONS (ticket_id, technician_id, resolution_notes, resolved_at)
    VALUES (p_ticket_id, p_technician_id, p_resolution_notes, SYSTIMESTAMP);

    -- 6. Update Parent Ticket Status
    UPDATE TICKETS
    SET status = 'RESOLVED'
    WHERE ticket_id = p_ticket_id;

    COMMIT;
    p_status_message := 'SUCCESS: Incident #' || p_ticket_id || ' resolved by Technician #' || p_technician_id;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        p_status_message := 'ERROR: Ticket #' || p_ticket_id || ' or Technician #' || p_technician_id || ' not found in database.';
        RAISE_APPLICATION_ERROR(-20001, p_status_message);
    WHEN e_ticket_already_resolved THEN
        p_status_message := 'ERROR: Ticket #' || p_ticket_id || ' is already resolved or closed.';
        RAISE_APPLICATION_ERROR(-20002, p_status_message);
    WHEN e_invalid_technician THEN
        p_status_message := 'ERROR: Employee #' || p_technician_id || ' does not possess TECHNICIAN privileges.';
        RAISE_APPLICATION_ERROR(-20003, p_status_message);
    WHEN e_empty_notes THEN
        p_status_message := 'ERROR: Technical diagnosis/resolution notes cannot be blank.';
        RAISE_APPLICATION_ERROR(-20004, p_status_message);
    WHEN OTHERS THEN
        ROLLBACK TO before_incident_resolution;
        p_status_message := 'CRITICAL: Transaction aborted. Reason: ' || SQLERRM;
        RAISE_APPLICATION_ERROR(-20005, p_status_message);
END;
/

-- ----------------------------------------------------------------------------
-- 5. PL/SQL STORED FUNCTION: FN_CALCULATE_RESOLUTION_TIME
-- Deterministic business function returning exact turnaround hours.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION FN_CALCULATE_RESOLUTION_TIME (
    p_ticket_id IN NUMBER
) RETURN NUMBER IS
    v_hours NUMBER;
BEGIN
    SELECT ROUND((CAST(r.resolved_at AS DATE) - CAST(t.created_at AS DATE)) * 24, 2)
    INTO v_hours
    FROM TICKETS t
    JOIN TICKET_RESOLUTIONS r ON t.ticket_id = r.ticket_id
    WHERE t.ticket_id = p_ticket_id;

    RETURN v_hours;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL; -- Ticket has not been resolved yet
    WHEN OTHERS THEN
        RETURN NULL;
END;
/

-- ----------------------------------------------------------------------------
-- 6. PL/SQL EXPLICIT CURSOR PROCEDURE: SP_ESCALATE_STALE_TICKETS
-- Iterates through open tickets older than 24h using explicit cursor loop
-- and auto-escalates priority to 'CRITICAL'.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SP_ESCALATE_STALE_TICKETS (
    p_escalated_count OUT NUMBER
) IS
    CURSOR cur_stale_incidents IS
        SELECT ticket_id, priority_level, created_at
        FROM TICKETS
        WHERE status = 'OPEN'
          AND priority_level != 'CRITICAL'
          AND created_at < SYSTIMESTAMP - INTERVAL '1' DAY;

    v_rec cur_stale_incidents%ROWTYPE;
    v_count NUMBER := 0;
BEGIN
    OPEN cur_stale_incidents;
    LOOP
        FETCH cur_stale_incidents INTO v_rec;
        EXIT WHEN cur_stale_incidents%NOTFOUND;

        UPDATE TICKETS
        SET priority_level = 'CRITICAL'
        WHERE ticket_id = v_rec.ticket_id;

        v_count := v_count + 1;
        DBMS_OUTPUT.PUT_LINE('SLA Breach Alert: Escalated Ticket #' || v_rec.ticket_id || ' to CRITICAL priority.');
    END LOOP;
    CLOSE cur_stale_incidents;

    COMMIT;
    p_escalated_count := v_count;
END;
/
